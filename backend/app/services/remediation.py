from typing import List, Dict, Any
from app.models.schemas import (
    AuditScorecard,
    RemediationRule,
    RemediationPlaybookResponse,
)

class RemediationEngine:
    """Generates deterministic Python code transformations for detected data quality defects."""

    def generate_playbook(self, dataset_name: str, scorecard: AuditScorecard) -> RemediationPlaybookResponse:
        rules: List[RemediationRule] = []

        # 1. Duplicates
        if scorecard.duplicates_count > 0:
            rules.append(
                RemediationRule(
                    target_column="*",
                    issue_type="duplicates",
                    severity="high" if scorecard.duplicates_count > 10 else "medium",
                    rule_description=f"Drop {scorecard.duplicates_count} full-row duplicates to ensure row uniqueness.",
                    python_snippet="# Deduplicate entire dataset\ndf = df.drop_duplicates(keep='first').reset_index(drop=True)",
                )
            )

        # 2. Completeness / Imputation
        for comp in scorecard.completeness:
            if comp.null_rate > 0.02:
                col = comp.column
                rules.append(
                    RemediationRule(
                        target_column=col,
                        issue_type="missing_values",
                        severity="high" if comp.null_rate > 0.15 else "medium",
                        rule_description=f"Impute missing values in '{col}' ({comp.null_rate:.1%} null rate).",
                        python_snippet=(
                            f"# Imputation for column: {col}\n"
                            f"if pd.api.types.is_numeric_dtype(df['{col}']):\n"
                            f"    df['{col}'] = df['{col}'].fillna(df['{col}'].median())\n"
                            f"else:\n"
                            f"    df['{col}'] = df['{col}'].fillna('UNKNOWN')"
                        ),
                    )
                )

        # 3. Statistical Anomaly clipping
        for anom in scorecard.anomalies:
            col = anom.column
            lower_bound = round(anom.mean - 3.0 * anom.pstdev, 3)
            upper_bound = round(anom.mean + 3.0 * anom.pstdev, 3)
            rules.append(
                RemediationRule(
                    target_column=col,
                    issue_type="statistical_outlier",
                    severity="medium",
                    rule_description=f"Clip 3-sigma outliers in numeric feature '{col}' to range [{lower_bound}, {upper_bound}].",
                    python_snippet=(
                        f"# Clip outliers for {col}\n"
                        f"df['{col}'] = df['{col}'].clip(lower={lower_bound}, upper={upper_bound})"
                    ),
                )
            )

        # 4. PII Masking
        for pii in scorecard.pii_findings:
            col = pii.column
            rules.append(
                RemediationRule(
                    target_column=col,
                    issue_type="pii_redaction",
                    severity=pii.sensitivity,
                    rule_description=f"Apply {pii.recommended_mask} on sensitive column '{col}' for {pii.regulation} compliance.",
                    python_snippet=(
                        f"# Mask sensitive PII column: {col}\n"
                        f"def mask_{col.replace('-', '_')}(val):\n"
                        f"    if not val or pd.isna(val):\n"
                        f"        return val\n"
                        f"    s = str(val)\n"
                        f"    return s[:2] + '***' + s[-2:] if len(s) > 4 else '***'\n"
                        f"df['{col}'] = df['{col}'].apply(mask_{col.replace('-', '_')})"
                    ),
                )
            )

        # Construct full runnable Python script
        script_parts = [
            "# Auto-generated Data Quality Remediation Script",
            f"# Target Dataset: {dataset_name}",
            f"# Generated by: data-quality-auditor-alan-vo",
            "",
            "import pandas as pd",
            "import numpy as np",
            "",
            "def clean_dataset(input_path: str, output_path: str):",
            "    # Load dataset",
            "    if input_path.endswith('.csv'):",
            "        df = pd.read_csv(input_path)",
            "    else:",
            "        df = pd.read_json(input_path)",
            "",
            "    print(f'Loaded raw dataset with {len(df)} rows, {len(df.columns)} columns')",
            "",
        ]

        if not rules:
            script_parts.append("    # No defects detected; data is already clean\n    pass")
        else:
            for r in rules:
                script_parts.append(f"    # {r.rule_description}")
                indented = "\n".join("    " + line for line in r.python_snippet.splitlines())
                script_parts.append(indented)
                script_parts.append("")

        script_parts.extend([
            "    # Save cleaned output",
            "    if output_path.endswith('.csv'):",
            "        df.to_csv(output_path, index=False)",
            "    else:",
            "        df.to_json(output_path, orient='records', indent=2)",
            "    print(f'Successfully saved cleaned dataset to {output_path}')",
            "    return df",
            "",
            "if __name__ == '__main__':",
            "    import sys",
            "    inp = sys.argv[1] if len(sys.argv) > 1 else 'input_dataset.csv'",
            "    out = sys.argv[2] if len(sys.argv) > 2 else 'cleaned_dataset.csv'",
            "    clean_dataset(inp, out)",
        ])

        full_script = "\n".join(script_parts)

        return RemediationPlaybookResponse(
            dataset_name=dataset_name,
            rules=rules,
            full_script=full_script,
            advisory_notes=(
                "All deterministic remediation rules are reproducible and operate without LLM dependencies. "
                "Review business constraints before applying automated clipping or imputation to downstream ML models."
            ),
        )
